// 使用已有 Playwright 安装运行：PLAYWRIGHT_PACKAGE 可指定包绝对路径。
// 先启动 npm exec vite -- --config tests/exam-retry-ui.vite.config.mjs；只测试内存夹具。
import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import { mkdir } from 'node:fs/promises'
const require = createRequire(import.meta.url)
const { chromium } = require(process.env.PLAYWRIGHT_PACKAGE || 'playwright')
const browser = await chromium.launch({ headless: true,
  ...(process.env.PLAYWRIGHT_CHANNEL ? { channel: process.env.PLAYWRIGHT_CHANNEL } : {}) })
const context = await browser.newContext({ viewport: { width: 1280, height: 960 } })
const page = await context.newPage(), errors = []
page.on('pageerror', error => errors.push(error.message))
const base = 'http://127.0.0.1:5194/tests/exam-retry-ui.html'
const output = new URL('../../tmp/exam-ai-retry-qa/', import.meta.url)
await mkdir(output, { recursive: true })
try {
  await page.goto(`${base}?lose-response=1`)
  await page.getByRole('button', { name: '详情', exact: true }).click()
  await page.getByText('达到输出上限', { exact: true }).waitFor()
  await page.getByRole('button', { name: '手动重试未完成项' }).click()
  const dialog = page.getByRole('dialog', { name: '手动重试任务', exact: true })
  await dialog.getByText(/单次输出上限 8192/).waitFor()
  const submit = dialog.getByRole('button', { name: '确认并创建重试任务' })
  assert.equal(await submit.isDisabled(), true)
  await dialog.getByText('我有权使用这些资料，同意发送至上方模型服务，并接受本次重试预算', { exact: true }).click()
  await dialog.getByRole('spinbutton').nth(0).fill('10')
  await dialog.getByRole('spinbutton').nth(1).fill('150000')
  await page.screenshot({ path: new URL('retry-desktop.png', output).pathname.replace(/^\/([A-Za-z]:)/, '$1'), fullPage: true })
  await submit.click()
  await dialog.getByRole('button', { name: '确认上次重试提交' }).waitFor()
  assert.equal(await dialog.getByRole('spinbutton').nth(0).isDisabled(), true)
  await dialog.getByRole('button', { name: '确认上次重试提交' }).click()
  await page.getByText('已创建重试任务 6，原任务记录保留', { exact: true }).waitFor()
  const calls = await page.evaluate(() => window.__examRetryRequests)
  assert.equal(calls.length, 2)
  assert.deepEqual(calls[0].data, calls[1].data)
  assert.equal(calls[0].headers['Idempotency-Key'], calls[1].headers['Idempotency-Key'])
  assert.equal(calls[0].data.maxCalls, 10)
  assert.equal(calls[0].data.maxTokens, 150000)
  await page.goto(`${base}?uncertain=1`)
  await page.getByRole('button', { name: '重试', exact: true }).click()
  await dialog.getByText('我有权使用这些资料，同意发送至上方模型服务，并接受本次重试预算', { exact: true }).click()
  assert.equal(await dialog.getByRole('button', { name: '确认并创建重试任务' }).isDisabled(), true)
  await dialog.getByText('我已核对原任务记录，接受再次执行及可能重复计费的风险', { exact: true }).click()
  assert.equal(await dialog.getByRole('button', { name: '确认并创建重试任务' }).isEnabled(), true)
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: new URL('retry-mobile.png', output).pathname.replace(/^\/([A-Za-z]:)/, '$1'), fullPage: true })
  const mobileSubmit = dialog.getByRole('button', { name: '确认并创建重试任务' })
  await mobileSubmit.scrollIntoViewIfNeeded()
  const buttonBox = await mobileSubmit.boundingBox()
  assert.ok(buttonBox.y >= 0 && buttonBox.y + buttonBox.height <= 844, '手机端应能滚动到确认按钮')
  await page.screenshot({ path: new URL('retry-mobile-bottom.png', output).pathname.replace(/^\/([A-Za-z]:)/, '$1'), fullPage: true })
  await page.setViewportSize({ width: 1280, height: 960 })
  await page.goto(`${base}?doc=1`)
  await page.getByRole('button', { name: '重试', exact: true }).click()
  assert.equal(await dialog.getByRole('checkbox').count(), 0)
  await dialog.getByRole('button', { name: '确认并创建重试任务' }).click()
  await page.getByText('已创建重试任务 6，原任务记录保留', { exact: true }).waitFor()
  await page.goto(`${base}?mode=extract`)
  await page.getByText(/本次 9 个资料批次/).waitFor()
  assert.equal(await page.getByRole('spinbutton').nth(0).inputValue(), '9')
  assert.equal(await page.getByRole('spinbutton').nth(1).inputValue(), '132000')
  assert.equal(await page.getByRole('button', { name: '确认并提交' }).isDisabled(), true)
  assert.deepEqual(errors, [])
  console.log('PASS: 重试入口、预算估算、双重授权、响应丢失幂等、文档重试与桌面/手机渲染；无真实模型调用')
} finally { await context.close(); await browser.close() }
